"""
trainer_blindspot.py

Training and validation pipeline for the BlindSpot occupancy
classification model.

The model receives two consecutive fisheye-camera frames:

    image_prev
    image_curr

and predicts two raw occupancy logits:

    occupancy_logits[:, 0] -> FREE
    occupancy_logits[:, 1] -> OCCUPIED

Training configuration:

    - Loss:
        CrossEntropyLoss

    - Optimizer:
        SGD with momentum and Nesterov acceleration

    - Learning-rate scheduler:
        Linear warmup followed by linear decay

    - Model weight smoothing:
        Exponential Moving Average (EMA)

    - Best-model criterion:
        Validation F1 score

    - Validation metrics:
        Loss
        Accuracy
        Precision
        Recall
        F1 score
        TP, TN, FP, FN

The trainer consumes metadata files generated by parse_woodscape.py
and loads the data through load_woodscape.py.
"""

